// content/text_quizzes.mjs - 오리지널 텍스트 퀴즈 (영상·이미지 없이 질문 문장 + 해설)
//
// - 모든 문제·보기·해설은 직접 작성한 내용이다(외부 영상/이미지/문구를 가져오지 않음).
// - 공개는 자동으로 하지 않는다: `node scripts/submit_drafts.mjs` 가 초안으로 제출하고, 관리자 대시보드에서 사람이 검수 후 공개한다.
// - 정답 위치는 문제마다 달라지도록 결정적으로 섞는다(재빌드해도 같은 결과).
// - 새 퀴즈를 추가할 때는 사실관계를 한 번 더 확인하고, 설명(description)은 다른 퀴즈와 겹치지 않게 새로 쓴다.
//   (test/content.test.js 가 검증기 통과·설명 중복 여부를 자동으로 확인한다.)

function build(quizIndex, { title, description, items }) {
    return {
        kind: 'quiz',
        source: 'curated',
        draft: {
            title,
            description,
            questions: items.map(([questionText, answer, wrongs, explanation], i) => {
                const pos = (i + quizIndex) % 4;                      // 정답 위치 (0~3)
                const texts = [...wrongs];
                texts.splice(pos, 0, answer);
                return {
                    questionText,
                    answer,
                    explanation,
                    options: texts.map((text, k) => ({ id: 'ABCD'[k], text, isCorrect: k === pos })),
                };
            }),
        },
    };
}

